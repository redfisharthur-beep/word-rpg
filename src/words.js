export const WORDS=RAW.trim().split('\n').map(line=>{const i=line.indexOf('|');return [line.slice(0,i),line.slice(i+1)]});
const MEANINGS=[...new Set(WORDS.map(x=>x[1]))];
const shuffle=a=>{const c=[...a];for(let i=c.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[c[i],c[j]]=[c[j],c[i]];}return c};
export function wordDeck(){return shuffle(WORDS.map((_,i)=>i));}
export function makeQuestion(index){const [word,answer]=WORDS[index%WORDS.length];const pool=shuffle(MEANINGS.filter(x=>x!==answer));return {word,answer,options:shuffle([answer,...pool.slice(0,3)])};}
